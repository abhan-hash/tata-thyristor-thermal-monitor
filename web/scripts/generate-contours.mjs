#!/usr/bin/env node
// Generates public/textures/contours.svg: the static topographic texture
// behind every page (Requirement 15.7). Run once; the output is committed.
//
// A smooth height field (seeded Gaussian hills plus a gentle tilt) is traced
// with d3-contour, and each ring is smoothed with a closed basis curve. The
// seed is fixed, so re-running produces a byte-identical file.
//
// The file is used as a CSS mask, so its stroke colour only sets coverage;
// the visible colour comes from the --contour-stroke token.
//
// Usage: node scripts/generate-contours.mjs [outFile]
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { contours } from 'd3-contour'
import { curveBasis, curveBasisClosed, line } from 'd3-shape'

export const SEED = 20261121
const GRID_W = 160
const GRID_H = 100
const VIEW_W = 1600
const VIEW_H = 1000
const HILLS = 16
const LEVELS = 22
// Rings shorter than this many points are specks; drop them.
const MIN_RING_POINTS = 12

function mulberry32(seed) {
  let state = seed >>> 0
  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function heightField(seed) {
  const rand = mulberry32(seed)
  const hills = Array.from({ length: HILLS }, () => ({
    x: rand() * GRID_W,
    y: rand() * GRID_H,
    // Anisotropic spread so the hills read as ridges, not bullseyes.
    sx: 10 + rand() * 26,
    sy: 8 + rand() * 20,
    h: (rand() < 0.75 ? 1 : -0.6) * (0.5 + rand()),
  }))
  const values = new Float64Array(GRID_W * GRID_H)
  for (let j = 0; j < GRID_H; j++) {
    for (let i = 0; i < GRID_W; i++) {
      let v = 0.004 * i + 0.002 * j
      for (const hill of hills) {
        const dx = (i - hill.x) / hill.sx
        const dy = (j - hill.y) / hill.sy
        v += hill.h * Math.exp(-0.5 * (dx * dx + dy * dy))
      }
      values[j * GRID_W + i] = v
    }
  }
  return values
}

const sx = VIEW_W / (GRID_W - 1)
const sy = VIEW_H / (GRID_H - 1)
const closedPath = line()
  .x((p) => p[0] * sx)
  .y((p) => p[1] * sy)
  .curve(curveBasisClosed)
  .digits(0)
const openPath = line()
  .x((p) => p[0] * sx)
  .y((p) => p[1] * sy)
  .curve(curveBasis)
  .digits(0)

// d3-contour closes rings along the grid border; those border runs are not
// contour lines, so a ring that touches the border is split into open runs.
const onBorder = (p) => p[0] <= 0.5 || p[1] <= 0.5 || p[0] >= GRID_W - 1.5 || p[1] >= GRID_H - 1.5

/** Every other point is enough once the curve smooths it, and halves the file. */
const thin = (pts) => pts.filter((_, k) => k % 2 === 0 || k === pts.length - 1)

function ringToPath(ring) {
  const pts = ring.slice(0, -1) // the closed curve repeats the first point itself
  const start = pts.findIndex(onBorder)
  if (start === -1) return closedPath(thin(pts))
  // Rotate so the walk starts on the border, then collect interior runs.
  const rotated = [...pts.slice(start), ...pts.slice(0, start)]
  const out = []
  let run = []
  for (const p of rotated) {
    if (onBorder(p)) {
      if (run.length >= MIN_RING_POINTS) out.push(openPath(thin(run)))
      run = []
    } else run.push(p)
  }
  if (run.length >= MIN_RING_POINTS) out.push(openPath(thin(run)))
  return out.join('')
}

export function generateContoursSvg(seed = SEED) {
  const values = heightField(seed)
  let min = Infinity
  let max = -Infinity
  for (const v of values) {
    if (v < min) min = v
    if (v > max) max = v
  }
  const step = (max - min) / (LEVELS + 1)
  const thresholds = Array.from({ length: LEVELS }, (_, k) => min + step * (k + 1))
  const paths = []
  for (const level of contours().size([GRID_W, GRID_H]).thresholds(thresholds)(values)) {
    const rings = []
    for (const polygon of level.coordinates) {
      for (const ring of polygon) {
        if (ring.length < MIN_RING_POINTS) continue
        const d = ringToPath(ring)
        if (d) rings.push(d)
      }
    }
    if (rings.length > 0) paths.push(`<path d="${rings.join('')}"/>`)
  }
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VIEW_W} ${VIEW_H}" preserveAspectRatio="xMidYMid slice">`,
    `<!-- Generated by scripts/generate-contours.mjs, seed ${seed}. Do not edit by hand. -->`,
    '<g fill="none" stroke="white" stroke-width="1.4" stroke-linejoin="round">',
    ...paths,
    '</g>',
    '</svg>',
    '',
  ].join('\n')
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
  const out = resolve(process.argv[2] ?? resolve(root, 'public/textures/contours.svg'))
  mkdirSync(dirname(out), { recursive: true })
  const svg = generateContoursSvg()
  writeFileSync(out, svg)
  console.log(`generate-contours: wrote ${out} (${(svg.length / 1024).toFixed(1)} KiB)`)
}
